#!/usr/bin/env node
/**
 * Downloads the local Whisper ONNX model used for offline speech input and
 * writes a generated manifest with the real byte size and sha256 of every
 * file that ends up on disk.
 *
 *   node scripts/fetch-local-asr-model.mjs [--force] [--model <repo>]
 *
 * The script is idempotent: a file whose sha256 already matches the manifest
 * is left alone and not re-downloaded.
 */

import { createHash } from 'node:crypto';
import { createReadStream, createWriteStream } from 'node:fs';
import { mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { pipeline as streamPipeline } from 'node:stream/promises';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, '..');
const PUBLIC_MODELS_DIR = join(ROOT, 'public', 'models');
const MANIFEST_PATH = join(ROOT, 'src', 'generated', 'asrModelManifest.ts');

/**
 * onnx-community/whisper-tiny is the multilingual (not `.en`) Whisper tiny
 * export, so one download covers hi/ta/te/mr/bn/en. transformers.js asks a
 * Seq2Seq model for `onnx/encoder_model<suffix>.onnx` and
 * `onnx/decoder_model_merged<suffix>.onnx`; for the wasm execution provider
 * the resolved dtype is q8, whose suffix is `_quantized`.
 */
const DEFAULT_MODEL = {
  repo: 'onnx-community/whisper-tiny',
  dir: 'whisper-tiny',
  files: [
    'config.json',
    'generation_config.json',
    'preprocessor_config.json',
    'tokenizer.json',
    'tokenizer_config.json',
    'onnx/encoder_model_quantized.onnx',
    'onnx/decoder_model_merged_quantized.onnx',
  ],
};

const HF_BASE = 'https://huggingface.co';

function parseArgs(argv) {
  const args = { force: false, model: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--force') args.force = true;
    else if (argv[i] === '--model') args.model = argv[++i];
  }
  return args;
}

function human(bytes) {
  return `${(bytes / (1024 * 1024)).toFixed(2)} MiB`;
}

async function sha256OfFile(filePath) {
  const hash = createHash('sha256');
  await streamPipeline(createReadStream(filePath), hash);
  return hash.digest('hex');
}

async function download(repo, file, destPath) {
  const url = `${HF_BASE}/${repo}/resolve/main/${file}`;
  const res = await fetch(url, { redirect: 'follow' });
  if (!res.ok || !res.body) {
    throw new Error(`GET ${url} -> HTTP ${res.status}`);
  }
  const tmp = `${destPath}.part`;
  await rm(tmp, { force: true });
  await streamPipeline(ReadableStreamToNode(res.body), createWriteStream(tmp));
  await rename(tmp, destPath);
}

function ReadableStreamToNode(webStream) {
  // Node's stream/promises pipeline accepts an async iterable; a web
  // ReadableStream is not one, so bridge it manually.
  return (async function* () {
    const reader = webStream.getReader();
    try {
      while (true) {
        const { done, value } = await reader.read();
        if (done) return;
        yield value;
      }
    } finally {
      reader.releaseLock();
    }
  })();
}

/** Reads back the files array this script previously generated, if any. */
async function readManifest() {
  try {
    const raw = await readFile(MANIFEST_PATH, 'utf8');
    const start = raw.indexOf('export const ASR_MODEL_FILES');
    if (start < 0) return null;
    const assign = raw.indexOf('=', start);
    const open = raw.indexOf('[', assign);
    const close = raw.indexOf('];', open);
    if (assign < 0 || open < 0 || close < 0) return null;
    return JSON.parse(raw.slice(open, close + 1));
  } catch {
    return null;
  }
}

function renderManifest(model, entries, totalBytes) {
  const repo = model.repo;
  const dir = model.dir;
  return `// AUTO-GENERATED by scripts/fetch-local-asr-model.mjs — do not edit by hand.
// Run \`npm run models:fetch\` after changing the model definition in that script.

export interface AsrModelFile {
  /** Path relative to /models/, exactly as transformers.js requests it. */
  readonly path: string;
  readonly size: number;
  readonly sha256: string;
}

export const ASR_MODEL_REPO = ${JSON.stringify(repo)};

export const ASR_MODEL_DIR = ${JSON.stringify(dir)};

export const ASR_MODEL_FILES: readonly AsrModelFile[] = ${JSON.stringify(entries, null, 2)};

export const ASR_MODEL_TOTAL_BYTES = ${totalBytes};
`;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const model = args.model ? { ...DEFAULT_MODEL, repo: args.model, dir: 'whisper-tiny' } : DEFAULT_MODEL;
  const destDir = join(PUBLIC_MODELS_DIR, model.dir);

  const previous = await readManifest();
  const previousByPath = new Map((previous ?? []).map((f) => [f.path, f]));

  await mkdir(join(destDir, 'onnx'), { recursive: true });

  const entries = [];
  let totalBytes = 0;

  for (const file of model.files) {
    const destPath = join(destDir, file);
    await mkdir(dirname(destPath), { recursive: true });

    let size = null;
    let sha256 = null;

    if (!args.force) {
      try {
        const st = await stat(destPath);
        size = st.size;
        const prev = previousByPath.get(file);
        if (prev && prev.size === size) {
          sha256 = await sha256OfFile(destPath);
          if (sha256 === prev.sha256) {
            console.log(`ok       ${file} (${human(size)}, sha256 matches)`);
          } else {
            console.log(`stale    ${file} (sha256 changed, re-downloading)`);
            size = null;
          }
        } else {
          console.log(`unknown  ${file} (no manifest entry, re-downloading)`);
          size = null;
        }
      } catch {
        size = null;
      }
    }

    if (size === null || sha256 === null) {
      console.log(`fetch    ${file}`);
      await download(model.repo, file, destPath);
      const st = await stat(destPath);
      size = st.size;
      sha256 = await sha256OfFile(destPath);
      console.log(`saved    ${file} (${human(size)})`);
    }

    entries.push({ path: file, size, sha256 });
    totalBytes += size;
  }

  await mkdir(dirname(MANIFEST_PATH), { recursive: true });
  await writeFile(MANIFEST_PATH, renderManifest(model, entries, totalBytes), 'utf8');

  console.log('');
  console.log(`model:  ${model.repo} -> public/models/${model.dir}`);
  console.log(`total:  ${human(totalBytes)} across ${entries.length} files`);
  console.log(`manifest: ${MANIFEST_PATH}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
