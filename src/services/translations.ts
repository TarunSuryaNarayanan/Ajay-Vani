export function getDashboardText(lang: LanguageCode, key: string): string {
  const langMap = DASHBOARD_TRANSLATIONS[lang] || DASHBOARD_TRANSLATIONS['hi-IN'];
  return langMap[key] || DASHBOARD_TRANSLATIONS['hi-IN'][key] || key;
}

export function formatText(lang: LanguageCode, key: string, ...values: (string | number)[]): string {
  let out = getDashboardText(lang, key);
  values.forEach((v) => {
    out = out.replace('%s', String(v));
  });
  return out;
}
