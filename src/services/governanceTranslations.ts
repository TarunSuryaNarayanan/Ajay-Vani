export function getGovText(lang: LanguageCode, key: string): string {
  const langMap = GOVERNANCE_TRANSLATIONS[lang] || GOVERNANCE_TRANSLATIONS['hi-IN'];
  return langMap[key] || GOVERNANCE_TRANSLATIONS['hi-IN'][key] || key;
}

/** Fills %s placeholders left-to-right. */
export function formatGovText(lang: LanguageCode, key: string, ...values: (string | number)[]): string {
  let out = getGovText(lang, key);
  values.forEach((v) => {
    out = out.replace('%s', String(v));
  });
  return out;
}
